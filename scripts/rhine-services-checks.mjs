import assert from 'node:assert/strict'
import { join } from 'node:path'

/** Operates only the isolated profile owned by rhine-music-smoke. */
export async function checkRhineServices({ page, frame, profile }) {
  await frame.getByRole('tab', { name: '电台', exact: true }).click()
  await frame.getByText('添加电台 / ADD STATION', { exact: true }).click()
  await frame.getByLabel('电台名称', { exact: true }).fill('Rhine regression station')
  await frame.getByLabel('流媒体地址', { exact: true }).fill('https://example.invalid/silent.wav')
  await frame.getByRole('button', { name: '添加电台', exact: true }).click()
  await frame.getByRole('button', { name: 'Rhine regression station', exact: true }).waitFor()
  let saved = await page.evaluate(() => window.api.radio.loadStations())
  assert.ok(saved.data.stations.some(s => s.name === 'Rhine regression station'))
  await page.screenshot({path:join(profile,'workspace-radio.png')})
  const station = frame.locator('.host-track').filter({hasText:'Rhine regression station'})
  await station.getByRole('button', {name:'移除', exact:true}).click()
  await frame.getByRole('button', { name: 'Rhine regression station', exact: true }).waitFor({state:'detached'})
  saved = await page.evaluate(() => window.api.radio.loadStations())
  assert.ok(!saved.data.stations.some(s => s.name === 'Rhine regression station'))

  await frame.getByRole('tab', { name: '播客', exact: true }).click()
  await frame.getByLabel('RSS 地址').fill('invalid feed')
  await frame.getByRole('button', {name:'订阅', exact:true}).click()
  await frame.locator('.host-status').filter({hasText:/错误|无效|地址|http/i}).waitFor()
  // The draft survives tab switches, and errors are not erased by a stale request.
  await frame.getByRole('tab', { name: '网络音乐源', exact: true }).click()
  await frame.getByText('添加网络音乐源 / CONNECT',{exact:true}).click()
  await frame.getByLabel('连接名称').fill('Rhine regression NAS')
  await frame.getByLabel('服务器地址').fill('https://example.invalid')
  await frame.getByRole('button', {name:'保存连接',exact:true}).click()
  await frame.getByText('Rhine regression NAS / WEBDAV',{exact:true}).waitFor()
  const profiles = await page.evaluate(() => window.api.networkSources.listProfiles())
  assert.ok(profiles.some(p => p.name === 'Rhine regression NAS'))
  await frame.getByText('Rhine regression NAS / WEBDAV',{exact:true}).click()
  await page.screenshot({path:join(profile,'workspace-network.png')})
  await frame.getByRole('button', {name:'移除连接',exact:true}).click()
  await frame.getByText('Rhine regression NAS / WEBDAV',{exact:true}).waitFor({state:'detached'})
  await frame.getByRole('tab', { name: '播客', exact: true }).click()
  assert.equal(await frame.getByLabel('RSS 地址').inputValue(),'invalid feed')

  await frame.getByRole('tab', { name: '聆听统计', exact: true }).click()
  await frame.locator('.host-activity > div').first().waitFor()
  assert.equal(await frame.locator('.host-activity > div').count(),30)
  await page.screenshot({path:join(profile,'workspace-stats.png')})
  await frame.getByRole('tab', { name: '诊断', exact: true }).click()
  await frame.getByLabel('问题描述').fill('Rhine automated isolated smoke')
  await frame.getByRole('button', {name:'标记问题',exact:true}).click()
  await frame.getByText('问题已标记',{exact:true}).waitFor()

  await frame.getByRole('tab', { name: '应用设置', exact: true }).click()
  await frame.getByLabel('本次分钟数').fill('5')
  await frame.getByRole('button', {name:'开启定时',exact:true}).click()
  await page.waitForFunction(async()=>!!(await window.api.sleepTimer.getState())?.active)
  await frame.getByRole('button', {name:'取消定时',exact:true}).click()
  await page.waitForFunction(async()=>(await window.api.sleepTimer.getState())===null)
  await frame.getByLabel('文件命名',{exact:true}).selectOption('artist-title')
  await page.waitForFunction(async()=>(await window.api.settings.get()).settings.downloadPreferences.naming==='artist-title')
  await frame.getByLabel('启动界面',{exact:true}).selectOption('rhine')
  await page.waitForFunction(async()=>(await window.api.settings.get()).settings.startupExperience?.experienceId==='rhine-lab')
  await frame.getByLabel('启动界面',{exact:true}).selectOption('default')
  await page.waitForFunction(async()=>(await window.api.settings.get()).settings.startupExperience===null)
  await page.screenshot({path:join(profile,'workspace-settings.png')})
  await frame.getByRole('tab', {name:'主题工具',exact:true}).click()
  await frame.getByRole('button',{name:'新建主题',exact:true}).click()
  const project = frame.locator('#host-page-themes details').first()
  await project.locator('summary').click()
  await project.getByRole('button',{name:'编辑配色与参数',exact:true}).click()
  await project.getByLabel('编辑模式',{exact:true}).waitFor()
  await project.getByLabel('编辑模式',{exact:true}).selectOption('dark')
  const save = project.getByRole('button',{name:/^保存/}).first()
  await save.click()
  await project.getByText('已保存',{exact:true}).waitFor()
  const projects = await page.evaluate(()=>window.api.themeWorkshop.list())
  assert.ok(projects.length>0)
  await page.screenshot({path:join(profile,'workspace-themes.png')})
  console.log('service checks passed: persisted radio/network CRUD, podcast errors, draft retention, stats, diagnostics, sleep timer, startup/settings')
}
